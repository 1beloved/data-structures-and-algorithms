//★一个奇异的三位数
//一个自然数的七进制表达式是一个三位数
//而这个自然数的九进制表示也是一个三位数
//且这两个三位数的数码正好相反，求这个三位数。
#include <stdio.h>
int main()
{
	int i,j,k;
	for(i=1;i<=9;i++)
	{
		for(j=0;j<=9;j++)
		{
			for(k=0;k<=9;k++)
			{
				if(i*7*7+7*j+k==i+j*9+k*9*9)
				{
					printf("%d%d%d(7)=%d%d%d(9)=%d(10)\n",k,j,i,i,j,k,i*9*9+j*9+k); 
				}
			}
		}
		
		
		
	}
		
	
}
