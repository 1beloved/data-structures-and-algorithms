//在数学上，有一个称为角谷猜想(最早由日本数学家角谷静夫提出)的经典题，
//其内容是：“对任意的正整数n，若为偶数，则把它除以2，若为奇数，则把它乘以3加1。
//经过如此有限次运算后，总可以得到正整数值1”
//输入3 
//for example：3*3+1=10
//
//10/2=5
//
//5*3+1=16
//
//16/2=8
//
//8/2=4
//
//4/2=2
//
//2/2=1 


#include <stdio.h>
int main()
{
	int n;
	scanf("%d",&n);
	while(n>1)
	{
		if(n%2==0)
		{
			printf("%d/2=%d\n",n,n/2);
			n=n/2;
		}
		else{
			printf("%d*3+1=%d\n",n,n*3+1);
			n=n*3+1;
		}
	}
}

