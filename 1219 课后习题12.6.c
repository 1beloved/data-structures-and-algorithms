//设计一个函数，使得给出一个16位整数的原码，能够得到该数的补码。
//一个只包含0和1的16位字符串，表示整数的原码。
//输入：1000000000011111    输出：1111111111100001 
#include <stdio.h>
int main()
{
	char a[17],*p=a;
	int flag;
	gets(a);
	flag=*p-'0';
	if(flag)//这是符号位为1时 
	{
		p++;//先到下一个位置 
		while(*p)//取反 
		{
			if(*p-'0')
				*p='0';
			else
				*p='1';
			p++;
		}
		p--;
		if(*p=='0') *p='1';
		else{
			while(*p=='1')
			{
				*p='0';
				p--;
			}
			*p='1';
		} 
	}
	puts(a);	
}
